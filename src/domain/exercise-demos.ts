// Fotos del ejercicio por su nombre (sin importar mayúsculas ni tildes), o null.
export function demoFor(name: string): [string, string] | null {
  const slug = DEMOS.get(normalizeName(name));
  return slug ? ["/ejercicios/" + slug + "-0.webp", "/ejercicios/" + slug + "-1.webp"] : null;
}
